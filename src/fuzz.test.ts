/** Exemple valide abîmé par une suite d'opérations aléatoires. */
function damaged(seed: string): fc.Arbitrary<string> {
  const operation = fc.oneof(
    fc.record({
      kind: fc.constant("insert" as const),
      at: fc.nat(),
      text: fc.string({ unit: "binary", maxLength: 40 }),
    }),
    fc.record({ kind: fc.constant("delete" as const), at: fc.nat(), length: fc.nat({ max: 60 }) }),
    fc.record({ kind: fc.constant("dropLine" as const), at: fc.nat() }),
    fc.record({
      kind: fc.constant("dupLine" as const),
      at: fc.nat(),
      times: fc.integer({ min: 1, max: 50 }),
    }),
    fc.record({ kind: fc.constant("swapLines" as const), a: fc.nat(), b: fc.nat() }),
    fc.record({ kind: fc.constant("truncate" as const), at: fc.nat() }),
    fc.record({
      kind: fc.constant("numbers" as const),
      value: fc.constantFrom(
        "nan",
        "-0",
        "1e309",
        "-1e309",
        "99999999999999999999",
        "0x1f",
        "",
        "1,5",
        "--1",
      ),
    }),
  );
  return fc.array(operation, { maxLength: 8 }).map((ops) => {
    let text: string = seed;
    for (const op of ops) {
      const lines = text.split("\n");
      const pos = (n: number) => (text.length === 0 ? 0 : n % (text.length + 1));
      const line = (n: number) => (lines.length === 0 ? 0 : n % lines.length);
      switch (op.kind) {
        case "insert":
          text = text.slice(0, pos(op.at)) + op.text + text.slice(pos(op.at));
          break;
        case "delete":
          text = text.slice(0, pos(op.at)) + text.slice(pos(op.at) + op.length);
          break;
        case "dropLine":
          lines.splice(line(op.at), 1);
          text = lines.join("\n");
          break;
        case "dupLine":
          lines.splice(
            line(op.at),
            0,
            ...Array.from({ length: op.times }, () => lines[line(op.at)] ?? ""),
          );
          text = lines.join("\n");
          break;
        case "swapLines": {
          const a = line(op.a);
          const b = line(op.b);
          [lines[a], lines[b]] = [lines[b] ?? "", lines[a] ?? ""];
          text = lines.join("\n");
          break;
        }
        case "truncate":
          text = text.slice(0, pos(op.at));
          break;
        case "numbers":
          text = text.replace(/-?\d+(\.\d+)?/, op.value);
          break;
      }
    }
    return text;
  });
}

/** Texte quelconque ou exemple abîmé. */
const input = (seed: string) =>
  fc.oneof(
    { weight: 1, arbitrary: fc.string({ unit: "binary", maxLength: 300 }) },
    {
      weight: 1,
      arbitrary: fc.string({
        unit: fc.constantFrom(
          "[",
          "]",
          ":",
          "=",
          "{",
          "}",
          "%",
          "#",
          "\n",
          " ",
          "\t",
          "a",
          "0",
          ".",
          "-",
          "!",
          "^",
          "*",
        ),
        maxLength: 300,
      }),
    },
    { weight: 3, arbitrary: damaged(seed) },
  );

const never = (run: (text: string) => unknown, seed: string) => () =>
  fc.assert(
    fc.property(input(seed), (text) => void run(text)),
    { numRuns: RUNS },
  );

describe("fuzzing des parseurs : aucune exception, quelle que soit l'entrée (EP-19.04)", () => {
  it(
    "configuration : lecture avec inclusions, validation, broches, mécanique",
    never((text) => {
      const files = new Map([
        ["printer.cfg", text],
        ["macros.cfg", text.slice(0, 200)],
      ]);
      const read = readConfig({ files, main: "printer.cfg" });
      const sections = parseConfig(text);
      validateConfig(sections, KLIPPER_SCHEMA);
      checkPins(sections);
      extractPrinterMechanics(sections);
      for (const line of text.split("\n").slice(0, 20)) parsePin(line);
      return read;
    }, SEEDS.config),
    TIMEOUT,
  );

  it(
    "BED_MESH_OUTPUT et profils SAVE_CONFIG",
    never((text) => {
      parseBedMeshOutput(text);
      parseMeshProfiles(text);
    }, `${SEEDS.mesh}\n${SEEDS.config}`),
    TIMEOUT,
  );

  it(
    "PROBE_ACCURACY",
    never((text) => parseProbeAccuracy(text), SEEDS.probe),
    TIMEOUT,
  );

  it(
    "journal klippy.log",
    never((text) => readKlippyLog(text), SEEDS.log),
    TIMEOUT,
  );

  it(
    "G-code : trajectoire et métadonnées, octets quelconques",
    never((text) => {
      // Octets quelconques (sans TextEncoder, absent des types du paquet autonome).
      const bytes = Uint8Array.from(text, (char) => char.charCodeAt(0) & 0xff);
      parseGcode(bytes);
      readGcodeMetadata(bytes);
    }, SEEDS.gcode),
    TIMEOUT,
  );

  it(
    "macros : modèles Jinja (Klipper et Kalico) et littéraux Python",
    never((text) => {
      lintTemplate(text, JINJA_ENVIRONMENTS.klipper);
      lintTemplate(text, JINJA_ENVIRONMENTS.kalico);
      checkMacroLiteral(text);
    }, SEEDS.jinja),
    TIMEOUT,
  );
});
